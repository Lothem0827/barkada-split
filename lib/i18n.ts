export function t(lang: Lang, key: CopyKey) {
  if (lang === "ceb") return ceb[key] || copy.tl[key]
  return copy[lang][key]
}

export function takenNicknameMessage(lang: Lang, existing: string, vsYou: boolean) {
  return t(lang, vsYou ? "nameTakenYou" : "nameTakenFriend").replaceAll("{name}", existing)
}

export function sulkMeta(lang: Lang, days: number) {
  const level = days <= 1 ? 0 : days <= 3 ? 1 : days <= 6 ? 2 : days <= 13 ? 3 : 4
  return { level, name: t(lang, SULK_KEYS[level]), emoji: SULK_EMOJI[level] }
}

export function personaLabel(lang: Lang, persona: Persona) {
  return t(lang, persona)
}

export function barkadaCountLabel(lang: Lang, members: { claimedByUid?: string | null }[]) {
  const joined = members.filter((member) => member.claimedByUid).length
  return t(lang, "barkadaCount")
    .replace("{n}", String(members.length))
    .replace("{joined}", String(joined))
    .replace("{left}", String(members.length - joined))
}
